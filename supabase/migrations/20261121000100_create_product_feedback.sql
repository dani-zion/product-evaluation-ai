-- Feedback: product evaluations (see specs/feedback.md and plans/feedback.md)
create table if not exists public.product_feedback (
  id          text primary key,                                              -- nanoid, generated by the API
  product_id  text not null references public.products (id) on delete cascade,
  account_id  text not null references public.accounts (id),
  score       smallint not null,
  comment     text not null,                                                 -- trimmed by the API
  created_at  timestamptz not null default now(),

  constraint product_feedback_score_range
    check (score between 1 and 5),
  constraint product_feedback_comment_length
    check (char_length(comment) between 3 and 1000)
);

-- The details page lists a product's evaluations newest first.
create index if not exists product_feedback_product_id_created_at_idx
  on public.product_feedback (product_id, created_at desc);

-- account_id is a foreign key; index it so account lookups and deletes stay fast.
create index if not exists product_feedback_account_id_idx
  on public.product_feedback (account_id);

-- Keep products.score equal to the rounded average of the product's evaluations
-- (null when there are none), so home cards need no extra query.
create or replace function public.refresh_product_score()
returns trigger
language plpgsql
as $$
declare
  target_product_id text;
begin
  if tg_op = 'DELETE' then
    target_product_id := old.product_id;
  else
    target_product_id := new.product_id;
  end if;

  update public.products
     set score = (
       select round(avg(score))::smallint
         from public.product_feedback
        where product_id = target_product_id
     )
   where id = target_product_id;

  return null;
end;
$$;

drop trigger if exists product_feedback_refresh_product_score on public.product_feedback;
create trigger product_feedback_refresh_product_score
  after insert or delete on public.product_feedback
  for each row execute function public.refresh_product_score();

-- No policies: only the server (service role key) can read or write evaluations.
alter table public.product_feedback enable row level security;
