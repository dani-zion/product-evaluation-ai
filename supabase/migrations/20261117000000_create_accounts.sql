-- Sign-up: accounts table (see specs/sign-up.md)
create table if not exists public.accounts (
  id          text primary key,                 -- nanoid, generated by the API
  first_name  text not null,
  last_name   text not null,
  email       text not null unique,             -- stored lowercased by the API
  password    text not null,                    -- bcrypt hash
  salt        text not null,                    -- bcrypt salt used for the hash
  active      boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- Keep updated_at current on every update.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists accounts_set_updated_at on public.accounts;
create trigger accounts_set_updated_at
  before update on public.accounts
  for each row execute function public.set_updated_at();

-- No policies: only the server (service role key) can read or write accounts.
-- The public anon key gets no access to password hashes.
alter table public.accounts enable row level security;
