-- Home: products table (see specs/home.md and plans/home.md)
create table if not exists public.products (
  id             text primary key,                -- nanoid, generated by the API
  name           text not null,
  description    text,
  image_url      text,                            -- absolute https:// URL, or null for a placeholder
  external_link  text not null,                   -- absolute http(s):// URL
  score          smallint,                        -- average evaluation, 1-5; null = no evaluations yet
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),

  constraint products_name_length
    check (char_length(name) between 1 and 200),
  constraint products_description_length
    check (description is null or char_length(description) <= 2000),
  constraint products_image_url_https
    check (image_url is null or image_url ~* '^https://'),
  constraint products_external_link_http
    check (external_link ~* '^https?://'),
  constraint products_score_range
    check (score is null or score between 1 and 5)
);

-- Keyset pagination for the home page: order by (created_at desc, id desc).
create index if not exists products_created_at_id_idx
  on public.products (created_at desc, id desc);

-- Keep updated_at current on every update (function from the accounts migration).
drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at
  before update on public.products
  for each row execute function public.set_updated_at();

-- No policies: only the server (service role key) can read or write products.
alter table public.products enable row level security;
